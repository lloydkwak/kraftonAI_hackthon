# --------------------------------------------------------------------------- capture

def _course():
    path = DOCS / "examples" / "course.json"
    if not path.is_file():                               # pragma: no cover
        raise RuntimeError(f"{path} is missing; it ships with the kit")
    return coursefile.load(path)


def capture(course, condition: str, tick: int = DUMP_TICK):
    """`(meta, obs)` at `tick`, from the scoring loop itself."""
    from .agent import TutorialAgent

    got = {}

    def hook(t, meta, obs):
        if t == tick:
            got["meta"], got["obs"] = meta, obs

    res = run_episode(course, TutorialAgent(), condition=condition, seed=DUMP_SEED,
                      tick_limit=tick + 1, on_observation=hook)
    if "obs" not in got:                                 # pragma: no cover
        raise RuntimeError(f"the episode ended as {res.outcome} at {res.ticks} < {tick}")
    return got["meta"], got["obs"]


def _listify(v):
    if isinstance(v, dict):
        return {k: _listify(x) for k, x in v.items()}
    if isinstance(v, np.ndarray):
        return np.round(v, 4).tolist() if v.dtype.kind == "f" else v.tolist()
    if isinstance(v, (np.generic,)):
        return v.item()
    if isinstance(v, (list, tuple)):
        return [_listify(x) for x in v]
    return v


def _shape(v):
    a = np.asarray(v)
    return f"`{a.dtype}`", ("scalar" if a.shape == () else "×".join(str(n) for n in a.shape))


# --------------------------------------------------------------------------- helpers

def _table(head, rows):
    out = ["| " + " | ".join(head) + " |", "|" + "---|" * len(head)]
    out += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
    return out


def _hex(rgb):
    return "#%02X%02X%02X" % tuple(rgb)


def _fmt(v, nd=3):
    a = np.asarray(v)
    if a.shape == ():
        return f"{a.item():.{nd}f}" if a.dtype.kind == "f" else str(a.item())
    return "[" + ", ".join(f"{x:.{nd}f}" if a.dtype.kind == "f" else str(x)
                           for x in a.reshape(-1)[:6]) + (", …" if a.size > 6 else "") + "]"


