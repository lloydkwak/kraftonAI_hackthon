"""The participant documents, generated from the code.

The problem statement carries the task, the semantics and the behavioural warnings;
**every number** -- dtypes, shapes, ranges, palette values, beam counts, limits -- lives in
the kit's schema document and its example dumps. A document that restates numbers by hand
drifts from the code that produces them, so this module *is* the document: `usvnav docs`
writes `docs/` from the same constants and the same observation loop the scorer runs, and
`usvnav docs --check` reports any committed file that differs from what the code generates.

What is written:

    docs/OBSERVATION.md     the observation and action schema
    docs/examples/          one course, its reset metadata, and one observation per
                            condition, captured from `sim.run_episode`
    docs/RULES.md           the capability list, the interface, how the kit runs a submission;
                            contest rules are on the site, not here
    docs/RUNTIME.md         what a submission meets at scoring time
    docs/PACKAGING.md       the submission directory, its manifest, and every check the
                            local validator applies

The prose is here rather than in Markdown files because the prose *names the numbers*:
"180 beams" is a sentence in which 180 is `lidar.N_BEAMS`, and a sentence that carries a
value has to be built where the value is. Semantics that are not numbers -- why no-return
is the maximum range rather than zero -- are repeated from the statement deliberately,
because an agent built on the wrong reading is structurally wrong.
"""

